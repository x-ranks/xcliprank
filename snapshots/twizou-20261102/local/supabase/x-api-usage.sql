-- X API利用量の分類ログ。実行後、3004の利用状況画面で集計できます。
create table if not exists public.x_api_usage_logs (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  source text not null check (source in (
    'discovery', 'priority', 'curated_initial',
    'curated_incremental', 'author_lookup', 'x_publish'
  )),
  endpoint text not null,
  http_status integer not null default 0,
  post_count integer not null default 0,
  user_count integer not null default 0,
  duration_ms integer not null default 0,
  error_message text
);

create index if not exists x_api_usage_logs_created_at_idx
  on public.x_api_usage_logs(created_at desc);
create index if not exists x_api_usage_logs_source_idx
  on public.x_api_usage_logs(source, created_at desc);
