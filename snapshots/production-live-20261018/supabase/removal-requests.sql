create table if not exists public.removal_requests (
  id bigint generated by default as identity primary key,
  request_code uuid not null unique,
  reported_url text not null,
  x_post_id text not null,
  reason text not null check (reason in ('illegal', 'minor', 'nonconsensual', 'copyright', 'other')),
  details text not null check (char_length(details) between 20 and 1500),
  contact_email text not null,
  status text not null default 'pending' check (status in ('pending', 'reviewing', 'removed', 'rejected')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  review_note text
);

create index if not exists removal_requests_status_created_idx
  on public.removal_requests(status, created_at desc);

create index if not exists removal_requests_x_post_idx
  on public.removal_requests(x_post_id);

alter table public.removal_requests enable row level security;

comment on table public.removal_requests is
  'Public removal requests accepted only through the server API using the service role.';
