const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const m = {exports: {}};
new Function('module','exports',ts.transpileModule(fs.readFileSync(path.join(__dirname,'../lib/ranking-liquidity.ts'),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText)(m,m.exports);
const {buildLiquidRankings,liquidityClock}=m.exports;
const since='2026-10-03T00:00:00.000Z';
const post=(key,date,tier='S')=>({x_post_id:String(key),author_id:'author'+(Number(key)%30),adult_tier:tier,created_at:date});
const archive=Array.from({length:450},(_,i)=>post(i,'2026-09-28T00:00:00Z',i<200?'S':i<300?'A+':'A'));
function verify(n){
 const recent=Array.from({length:n},(_,i)=>post(i+10000,'2026-10-03T12:00:00Z','B'));
 const p=buildLiquidRankings(recent,archive,since,'2026-10-04');
 assert.ok(p.trending.length>=100);
 assert.equal(p.daily.length,100);
 assert.equal(p.metrics.dailyFixedArchive,85);
 assert.ok(p.metrics.newArchive>=50&&p.metrics.newArchive<=100);
 const ids=new Set(p.trending.map(x=>x.x_post_id));
 assert.equal(p.daily.filter(x=>ids.has(x.x_post_id)).length,0);
 assert.equal(ids.size,p.trending.length);
 for(const x of p.trending.filter(p=>p.ranking_supplemented))assert.ok(['S','A+','A'].includes(x.adult_tier));
 assert.deepEqual(p,buildLiquidRankings(recent,archive,since,'2026-10-04'));
 const next=buildLiquidRankings(recent,archive,since,'2026-10-05');
 assert.notDeepEqual(p.trending.filter(x=>x.ranking_slot==='random_archive').map(x=>x.x_post_id),next.trending.filter(x=>x.ranking_slot==='random_archive').map(x=>x.x_post_id));
 return p;
}
for(const n of [0,10,50,100,160,300])verify(n);
const stable=verify(20);assert.ok(stable.daily.filter(x=>x.ranking_slot==='fixed_archive').every(x=>x.adult_tier==='S'));
const short=buildLiquidRankings([],archive.slice(0,20),since,'2026-10-04');
assert.ok(short.metrics.trendingShortfall>0&&short.metrics.dailyShortfall>0);
const invalid=buildLiquidRankings([],archive.map(p=>({...p,adult_tier:'NONE'})),since,'2026-10-04');assert.equal(invalid.trending.length+invalid.daily.length,0);
const dup=buildLiquidRankings([], [...archive,...archive], since,'2026-10-04');assert.equal(new Set([...dup.trending,...dup.daily].map(p=>p.x_post_id)).size,200);
const a=liquidityClock(Date.parse('2026-10-03T14:59:59Z'));const b=liquidityClock(Date.parse('2026-10-03T15:00:00Z'));assert.equal(a.seed,'2026-10-03');assert.equal(b.seed,'2026-10-04');
console.log('PASS: 100+ counts; 50-100 random archive; 85 quality slots; zero overlap; day rotation; sparse pool; exclusion; duplicates; JST boundary');
