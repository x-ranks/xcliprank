create table if not exists public.x_promotion_logs (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  status text not null check (status in ('publishing', 'success', 'failed', 'skipped')),
  trigger_source text not null default 'manual' check (trigger_source in ('manual', 'cron')),
  variant text not null check (variant in ('a', 'b', 'c')),
  ranking_date date not null,
  ranking_signature text not null,
  dedupe_key text unique,
  ranking_count integer not null default 0,
  top_post_ids jsonb not null default '[]'::jsonb,
  target_url text not null,
  utm_content text not null,
  draft_text text not null,
  x_post_id text,
  x_post_url text,
  media_count integer not null default 0,
  error_message text
);

create index if not exists x_promotion_logs_created_idx
  on public.x_promotion_logs(created_at desc);

create index if not exists x_promotion_logs_status_created_idx
  on public.x_promotion_logs(status, created_at desc);

create index if not exists x_promotion_logs_utm_content_idx
  on public.x_promotion_logs(utm_content);

alter table public.x_promotion_logs enable row level security;

