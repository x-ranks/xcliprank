create table if not exists public.contact_requests (
  id bigint generated by default as identity primary key,
  request_code uuid not null unique,
  category text not null check (
    category in ('advertising', 'partnership', 'technical', 'other')
  ),
  name text check (name is null or char_length(name) <= 100),
  contact_email text not null,
  subject text not null check (char_length(subject) between 3 and 120),
  details text not null check (char_length(details) between 20 and 2000),
  status text not null default 'pending' check (
    status in ('pending', 'reviewing', 'resolved', 'closed')
  ),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  review_note text
);

create index if not exists contact_requests_status_created_idx
  on public.contact_requests(status, created_at desc);

alter table public.contact_requests enable row level security;

comment on table public.contact_requests is
  'Public contact requests accepted only through the server API using the service role.';
