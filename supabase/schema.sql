create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  x_post_id text not null unique,
  author_id text,
  author_username text,
  author_name text,
  text text,
  created_at timestamptz not null,
  x_url text not null,
  media_key text,
  media_type text,
  preview_image_url text,
  views bigint not null default 0,
  likes bigint not null default 0,
  reposts bigint not null default 0,
  replies bigint not null default 0,
  quotes bigint not null default 0,
  bookmarks bigint not null default 0,
  score bigint not null default 0,
  is_visible boolean not null default true,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);

create index if not exists posts_created_at_idx on public.posts(created_at desc);
create index if not exists posts_score_idx on public.posts(score desc);

create table if not exists public.metric_snapshots (
  id bigint generated by default as identity primary key,
  x_post_id text not null references public.posts(x_post_id) on delete cascade,
  measured_at timestamptz not null default now(),
  views bigint not null default 0,
  likes bigint not null default 0,
  reposts bigint not null default 0,
  replies bigint not null default 0,
  score bigint not null default 0
);

create index if not exists metric_snapshots_post_time_idx
  on public.metric_snapshots(x_post_id, measured_at desc);

alter table public.posts enable row level security;
alter table public.metric_snapshots enable row level security;

-- Public clients don't need direct table access in this MVP.
-- All reads are routed through Next.js server endpoints using the service role key.
