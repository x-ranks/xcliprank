-- Web Push の登録情報。通知を希望した端末だけが保存されます。
-- 保存するのは「端末の宛先(endpoint)・暗号鍵・フォロー中の投稿者キー」だけで、名前や連絡先は保存しません。
-- ブラウザからSupabaseへ直接アクセスさせず、Next.js APIがservice roleで読み書きします。
create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  follows text[] not null default '{}',
  created_at timestamptz not null default now(),
  notified_through timestamptz not null default now(),
  last_sent_at timestamptz,
  fail_count integer not null default 0
);

alter table public.push_subscriptions enable row level security;
-- public向けRLS policyは意図的に作成しません。
