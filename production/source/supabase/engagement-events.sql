create table if not exists public.engagement_events (
  id bigint generated by default as identity primary key,
  occurred_at timestamptz not null default now(),
  event_type text not null check (
    event_type in ('page_view', 'video_open', 'qualified_view', 'ranking_change', 'outbound_x')
  ),
  x_post_id text,
  anonymous_id_hash text not null,
  session_id text not null,
  source text,
  range text,
  metadata jsonb not null default '{}'::jsonb,
  dedupe_key text not null unique
);

create index if not exists engagement_events_type_time_idx
  on public.engagement_events(event_type, occurred_at desc);

create index if not exists engagement_events_post_time_idx
  on public.engagement_events(x_post_id, occurred_at desc)
  where x_post_id is not null;

create index if not exists engagement_events_anonymous_time_idx
  on public.engagement_events(anonymous_id_hash, occurred_at desc);

alter table public.engagement_events enable row level security;

